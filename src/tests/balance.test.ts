import { describe, expect, it } from 'vitest';
import { ARMOUR_MATERIALS, BLOCKS, TOOL_TIERS } from '../engine/blocks';
import { SPECIES } from '../creatures/species';
import { armourFactor, weaponDamage } from '../game/play';
import { MAX_HEALTH } from '../config';

/**
 * The balance sheet in docs/balance.md: hits to kill each hostile with each sword, and bites each one needs to kill the
 * player in each armour set (normal difficulty, full-strength hits, no crits). `npx vitest run -u` rewrites it.
 */
const SWORDS = TOOL_TIERS.map((t) => ({ name: t, damage: weaponDamage({ state: BLOCKS.state(`${t}_sword`), count: 1 }) }));
const SETS = [['none', 0] as const, ...Object.entries(ARMOUR_MATERIALS).map(([m, a]) => [m, a.protection.reduce((s, p) => s + p, 0)] as const)];
const hostiles = SPECIES.filter((s) => s.hostile && s.attack > 0);
const hits = (health: number, damage: number) => Math.ceil(health / damage);
const bites = (attack: number, points: number) => Math.ceil(MAX_HEALTH / (attack * armourFactor(points)));

function sheet(): string {
  const row = (cells: (string | number)[]) => `| ${cells.join(' | ')} |`;
  return [
    '# Balance sheet',
    '',
    'Generated by `src/tests/balance.test.ts` (`npx vitest run -u src/tests/balance.test.ts` rewrites this file). Normal difficulty,',
    `full-strength hits, no crits, ${MAX_HEALTH} health.`,
    '',
    '## Sword hits to kill',
    '',
    row(['Creature', 'Health', ...SWORDS.map((s) => `${s.name} (${s.damage})`)]),
    row(['---', '---:', ...SWORDS.map(() => '---:')]),
    ...hostiles.map((s) => row([s.boss || s.guardian ? `**${s.name}**` : s.name, s.health, ...SWORDS.map((w) => hits(s.health, w.damage))])),
    '',
    '## Bites to kill the player',
    '',
    row(['Creature', 'Bite', ...SETS.map(([m, p]) => `${m} (${Math.round((1 - armourFactor(p)) * 100)}%)`)]),
    row(['---', '---:', ...SETS.map(() => '---:')]),
    ...hostiles.map((s) => row([s.boss || s.guardian ? `**${s.name}**` : s.name, s.attack, ...SETS.map(([, p]) => bites(s.attack, p))])),
    '',
  ].join('\n');
}

describe('balance', () => {
  it('docs/balance.md is up to date', async () => {
    await expect(sheet()).toMatchFileSnapshot('../../docs/balance.md');
  });

  it('each gear tier is better than the one before', () => {
    for (let i = 1; i < SWORDS.length; i++) expect(SWORDS[i]!.damage).toBeGreaterThan(SWORDS[i - 1]!.damage);
    for (let i = 1; i < SETS.length; i++) expect(armourFactor(SETS[i]![1])).toBeLessThan(armourFactor(SETS[i - 1]![1]));
  });

  it('no ordinary monster kills an unarmoured player in fewer than three bites, and bosses take a real fight', () => {
    for (const s of hostiles.filter((s) => !s.boss && !s.guardian)) expect(bites(s.attack, 0), s.key).toBeGreaterThanOrEqual(3);
    const iron = SWORDS.find((w) => w.name === 'iron')!.damage, best = SWORDS.at(-1)!.damage;
    for (const s of hostiles.filter((s) => s.boss || s.guardian)) {
      expect(hits(s.health, best), s.key).toBeGreaterThanOrEqual(10);
      expect(hits(s.health, iron), s.key).toBeLessThanOrEqual(80);
    }
  });
});
